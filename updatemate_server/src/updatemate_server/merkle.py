class SoftwareRegistry:
    # Side index mapping software_version_id -> the raw_data of every
    # signature that version was submitted with. This is NOT part of the
    # tamper-evident ledger -- it is a small, plain-file, rebuildable-from
    # -the-ledger convenience index that exists purely so that verifying a
    # review's developer status doesn't require re-scanning an entire
    # product's Merkle tree on every submission. Its authoritative source
    # of truth remains the version data already appended to
    # `{software_name}_tree.db`; if this file were ever lost, it could be
    # regenerated by replaying that tree.
    VERSION_INDEX_FILENAME = "version_signing_index.json"

    def __init__(self, path: str):
        # Create data folder if it doesn't exist yet
        if not os.path.exists(path):
            os.makedirs(path)

        # Initialize / connect to main tree
        self.master_tree = SqliteTree(path + "master_tree.db")
        self.path = path

    def _load_version_index(self) -> dict:
        idx_path = self.path + self.VERSION_INDEX_FILENAME
        if os.path.isfile(idx_path):
            with open(idx_path, "r") as f:
                return json.load(f)
        return {}

    def _save_version_index(self, index: dict):
        idx_path = self.path + self.VERSION_INDEX_FILENAME
        with open(idx_path, "w") as f:
            json.dump(index, f)

    def get_version_signing_raw_data(self, software_version_id: str) -> list:
        """Every `signatures[].raw_data` blob submitted for this version,
        used to check whether a review's signing key is the same key that
        signed the binary itself. Returns [] for an unknown version."""
        return self._load_version_index().get(software_version_id, {}).get("raw_data", [])

    def add_software_version(self, software_version: SoftwareVersion): 
        software_name = software_version.file_properties.StringFileInfo["ProductName"]
        
        #Add first seen date to software/version
        now = datetime.now()
        current_time_string = now.strftime("%Y-%m-%d %H:%M:%S")
        software_version.first_seen = current_time_string

        # Consistent serialization for the audit log
        software_version_hash = software_version.signatures[0].hash
        software_version_id = software_name.replace(" ", "_")  + "-" + software_version_hash
        software_version.software_version_id = software_version_id

        software_data = json.dumps(software_version.__dict__, default=lambda o: o.__dict__, sort_keys=True) # Sort keys for consistent hashing

        with SqliteTree(self.path + f"master_tree.db") as master_tree:
            if not master_tree.get_entry(software_name.encode('utf-8')): # Check if software is already registered in Master Tree
                # REGISTER the new tree in the Master Tree, using the software's name
                master_tree.append_entry(software_name.encode('utf-8')) 
                print(f"[REGISTERED] {software_name} added to Master Tree.")
        

        with SqliteTree(self.path + f"{software_name}_tree.db") as software_tree:
            software_tree.append_entry(software_data.encode('utf-8')) # Create tree for software if needed. Add version
            print(f"[ADDED] Version {software_version_id} added to {software_name}'s tree.")

        # Record this version's signature blob(s) in the side index, so that
        # a later review submission can check whether it was signed with the
        # same key that signed this binary (see auth.is_developer_submission).
        index = self._load_version_index()
        index[software_version_id] = {
            "raw_data": [sig.raw_data for sig in software_version.signatures],
        }
        self._save_version_index(index)

        if not  os.path.isfile(self.path + f"{software_version_id}_reviews_tree.db"):
            with SqliteTree(self.path + f"{software_version_id}_reviews_tree.db") as reviews_tree:
                pass # Just create the tree for this version's reviews

    def add_version_review(self, software_version_id, review: SoftwareReview):

        if os.path.isfile(self.path + f"{software_version_id}_reviews_tree.db"):
            # Authenticate the submitter before anything else touches the
            # ledger. Reviews are identified by the keypair that signed
            # them, not by the free-text `reviewer` field, so a review
            # without a valid signature is rejected outright rather than
            # recorded as anonymous.
            if not review.signer_public_key or not review.signature:
                raise auth.SignatureError(
                    "Review submissions must be signed: 'signer_public_key' and "
                    "'signature' are required."
                )

            signature_ok = auth.verify_review_signature(
                software_version_id, review.reviewer, review.comment, review.review,
                review.signer_public_key, review.signature,
            )
            if not signature_ok:
                raise auth.SignatureError(
                    "Review signature does not verify against the provided public key."
                )

            review.signer_id = auth.public_key_fingerprint(
                auth.load_public_key_pem(review.signer_public_key)
            )
            raw_data_list = self.get_version_signing_raw_data(software_version_id)
            review.developer_verified = auth.is_developer_submission(
                review.signer_public_key, raw_data_list
            )

            # A valid signature only proves *who* signed this review -- it
            # doesn't bound how many reviews that "who" can cheaply produce,
            # since generating a fresh keypair is free (Section 8.1 of the
            # paper). A developer-verified review is already bound to a
            # scarce, high-value credential (the same key that signed the
            # reviewed binary), so we exempt it; everyone else must solve a
            # CAPTCHA challenge (updatemate_server/captcha.py) before their
            # review is accepted.
            if not review.developer_verified:
                if not review.captcha_challenge_id or not review.captcha_answer:
                    raise auth.CaptchaError(
                        "Non-developer-verified review submissions must include a solved "
                        "'captcha_challenge_id'/'captcha_answer' pair."
                    )
                captcha_ok = captcha.verify_and_consume(
                    review.captcha_challenge_id, review.captcha_answer
                )
                if not captcha_ok:
                    raise auth.CaptchaError(
                        "CAPTCHA answer is incorrect, expired, or already used."
                    )

            # Neither field carries lasting cryptographic evidence once
            # verified (captcha.py explains why), so we deliberately do not
            # persist them into the ledger entry below.
            if hasattr(review, "captcha_challenge_id"):
                del review.captcha_challenge_id
            if hasattr(review, "captcha_answer"):
                del review.captcha_answer

            with SqliteTree(self.path + f"{software_version_id}_reviews_tree.db") as software_tree:
                #Add received date
                now = datetime.now()
                current_time_string = now.strftime("%Y-%m-%d %H:%M:%S")
                review.time_received = current_time_string

                review_data = json.dumps(review.__dict__, default=lambda o: o.__dict__, sort_keys=True) # Sort keys for consistent hashing
                software_tree.append_entry(review_data.encode('utf-8'))

            return("OK")
        else:
            return f"{software_version_id} not found in system. You must first upload the version's data before submitting a comment."

    def get_human_readable_report(self, software_name, print_certs=True):
        """Standard lookup for an auditor"""
        output = ""

        if not os.path.isfile(self.path + f"{software_name}_tree.db"):
            output += f"Product {software_name} not found."
            return output

        with SqliteTree(self.path + f"{software_name}_tree.db") as software_tree:
            tree_size = software_tree.get_size()
            output += f"\n======Human readable report for {software_name}======\n"
            output += f"Total Versions: {tree_size}\n"
            output += f"Latest Root Hash: {software_tree.get_state().hex()}\n"

            for i in range(1, tree_size+1):
                version_data = json.loads(software_tree.get_entry(i).decode('utf-8'))
                software_version = SoftwareVersion(version_data)
                output += f"\n>>> Details for version: {software_version.file_properties.StringFileInfo['ProductVersion']}\n"
                output += f"First seen date: {version_data['first_seen']}\n"
                version_id = software_name.replace(" ", "_") + '-' + version_data["signatures"][0]["hash"]
                output += f"Version ID: {version_id}\n"
                output += f"Signature information:\n"
                output += f"\tSignature hash: {version_data['signatures'][0]['hash']}\n"
                if(print_certs):
                    output += f"\tCertificate chain:\n"
                    for certificate in version_data["signatures"][0]["certificates"]:
                        output += f"\t\tIssuer: {certificate['issuer']}\n"
                        output += f"\t\tSubject: {certificate['subject']}\n"
                        output += f"\t\tValid From: {certificate['valid_from']}\n"
                        output += f"\t\tValid To: {certificate['valid_to']}\n"

                #Get review data:
                output += f"\tReviews for version: \n"

                if not os.path.isfile(self.path + f"{version_id}_reviews_tree.db"):
                    output += f"\t\tNo reviews submitted yet!\n"
                else:
                    with SqliteTree(self.path + f"{version_id}_reviews_tree.db") as reviews_tree:
                        for i in range(0, reviews_tree.get_size()+1):
                            review = reviews_tree.get_entry(i)
                            output += f'\t\t{review}\n'

        #print(output)
        return output

    def get_software_versions(self, software_name):
        """Standard lookup for an auditor"""
        if not os.path.isfile(self.path + f"{software_name}_tree.db"):
            return f"Product {software_name} not found."

        with SqliteTree(self.path + f"{software_name}_tree.db") as software_tree:
            version_data = []
            for i in range(1, software_tree.get_size()+1):
                leaf = software_tree.get_entry(i)
                version_data.append(json.loads(leaf))
        
        #print(version_data)
        return version_data
    
    def get_version_reviews(self, software_version_id):
        """Standard lookup for an auditor"""

        reviews = []

        if os.path.isfile(self.path + f"{software_version_id}_reviews_tree.db"):
            with SqliteTree(self.path + f"{software_version_id}_reviews_tree.db") as software_tree:
                for i in range(1, software_tree.get_size()+1):
                    leaf = software_tree.get_entry(i)
                    reviews.append(json.loads(leaf))
        else:
            return f"{software_version_id} not found in system. You must first upload the version's data before submitting a comment."

        return reviews
    
    def get_root_audit(self):
        """Get the current state of the Master Tree, which contains all registered software products. This is the main audit result that can be publicly verified."""
        with SqliteTree(self.path + f"master_tree.db") as master_tree:
            root_hash = master_tree.get_state().hex()
            return {"root_hash": root_hash, "registered_software_count": master_tree.get_size(), "tree": Path(self.path + f"master_tree.db").read_bytes().hex()}
        
    def get_software_audit(self, software_name):
        """Get the audit result for a specific software product."""
        if not os.path.isfile(self.path + f"{software_name}_tree.db"):
            return f"Product {software_name} not found."

        with SqliteTree(self.path + f"{software_name}_tree.db") as software_tree:
            root_hash = software_tree.get_state().hex()
            return {"root_hash": root_hash, "versions_count": software_tree.get_size(), "tree": Path(self.path + f"{software_name}_tree.db").read_bytes().hex()}
        
    def get_software_version_audit(self, software_version_id):
        """Get the audit result for a specific software version."""
        if not os.path.isfile(self.path + f"{software_version_id}_reviews_tree.db"):
            return f"{software_version_id} not found in system. You must first upload the version's data before submitting a comment."

        with SqliteTree(self.path + f"{software_version_id}_reviews_tree.db") as reviews_tree:
            root_hash = reviews_tree.get_state().hex()
            return {"root_hash": root_hash, "reviews_count": reviews_tree.get_size(), "tree": Path(self.path + f"{software_version_id}_reviews_tree.db").read_bytes().hex()}
